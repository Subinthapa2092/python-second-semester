# Program to show the difference between positive and negative indexing with slicing.


text = "Python Programming"

print("Using Positive Indexing:")
print("text[0:6]  =", text[0:6])     
print("text[6:17] =", text[6:18])   

print("\nUsing Negative Indexing:")
print("text[-11:-5] =", text[-11:-5])  
print("text[-5:]    =", text[-5:])     
